/**
 * Regenerates the bundled migration manifests from the drizzle-kit migration folders:
 *
 * - SQLite: `apps/server/src/migrations/drizzle/` →
 *   `apps/server/src/migrations/drizzle-manifest.generated.ts`;
 * - Postgres [POD-6981]: `apps/server/src/migrations/pg/drizzle/` →
 *   `apps/server/src/migrations/pg/manifest.generated.ts`.
 *
 * WHY a generated module of inlined strings: the runtime appliers
 * (`migrations/index.ts`, `migrations/pg/index.ts`) must NOT read migration files from
 * disk — the `bun --compile` single binary carries no `drizzle/` folder. Inlining each
 * `migration.sql` as a JSON-escaped string literal makes the migrations bundle
 * into the binary and load identically under Bun and Node. `migration:new` and
 * `migration:pg-baseline` regenerate these, and CI checks they are not stale (`--check`).
 *
 * Usage: `bun run scripts/build-drizzle-manifest.ts [--check]`
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = join(HERE, '..')

interface Chain {
  readonly dir: string
  readonly out: string
  readonly render: (entries: string[]) => string
}

/** Migration folders in name order — the timestamp prefix makes this chronological. */
function migrationFolders(dir: string): string[] {
  return readdirSync(dir)
    .filter((name) => {
      const full = join(dir, name)
      return statSync(full).isDirectory()
    })
    .sort((a, b) => a.localeCompare(b))
}

const SQLITE: Chain = {
  dir: join(REPO, 'apps/server/src/migrations/drizzle'),
  out: join(REPO, 'apps/server/src/migrations/drizzle-manifest.generated.ts'),
  render: (entries) => `// GENERATED by scripts/build-drizzle-manifest.ts — do not edit by hand.
// Regenerate with \`bun run migration:new\` or \`bun run scripts/build-drizzle-manifest.ts\`.
import type { DrizzleMigration } from './index'

/** All drizzle migrations, bundled as strings, in chronological (name) order. */
export const DRIZZLE_MIGRATIONS: DrizzleMigration[] = [
${entries.join('\n')}
]

/**
 * The baseline — the verbatim dump of the schema as it stood when drizzle was
 * adopted. On an existing (legacy) database this is STAMPED, not executed,
 * because the legacy chain already built that schema.
 */
export const BASELINE_MIGRATION: DrizzleMigration = DRIZZLE_MIGRATIONS[0]!
`,
}

const POSTGRES: Chain = {
  dir: join(REPO, 'apps/server/src/migrations/pg/drizzle'),
  out: join(REPO, 'apps/server/src/migrations/pg/manifest.generated.ts'),
  render: (entries) => `// GENERATED by scripts/build-drizzle-manifest.ts — do not edit by hand.
// Regenerate with \`bun run migration:new\` or \`bun run scripts/build-drizzle-manifest.ts\`.
import type { DrizzleMigration } from '../index'

/**
 * The Postgres chain [POD-6981], bundled as strings, in chronological (name) order:
 * the baseline (the whole schema, generated from \`./schema.ts\`), then every later
 * migration, each named as its SQLite twin.
 */
export const PG_MIGRATIONS: DrizzleMigration[] = [
${entries.join('\n')}
]
`,
}

function render(chain: Chain): string {
  const folders = migrationFolders(chain.dir)
  const first = folders[0]
  if (first === undefined) {
    throw new Error(`no migration folders found under ${chain.dir}`)
  }
  if (!/_baseline$/.test(first)) {
    throw new Error(
      `the first migration must be the baseline (folder name ending in '_baseline'); ` +
        `got '${first}'. The baseline is stamped (not run) on existing databases, ` +
        `so it must sort first.`,
    )
  }
  const entries = folders.map((name) => {
    const sql = readFileSync(join(chain.dir, name, 'migration.sql'), 'utf8')
    return `  { name: ${JSON.stringify(name)}, sql: ${JSON.stringify(sql)} },`
  })
  return chain.render(entries)
}

const check = process.argv.includes('--check')
let stale = false
for (const chain of [SQLITE, POSTGRES]) {
  const content = render(chain)
  const name = relative(REPO, chain.out)
  if (check) {
    const current = (() => {
      try {
        return readFileSync(chain.out, 'utf8')
      } catch {
        return ''
      }
    })()
    if (current !== content) {
      console.error(`${name} is stale. Run \`bun run scripts/build-drizzle-manifest.ts\`.`)
      stale = true
    } else {
      console.log(`${name} is up to date.`)
    }
  } else {
    writeFileSync(chain.out, content)
    console.log(`wrote ${chain.out}`)
  }
}
if (stale) process.exit(1)
