const ROOT = fileURLToPath(new URL('../', import.meta.url))

/** One SQLite schema module and the Postgres file generated from it. */
export interface Target {
  readonly name: 'server' | 'sync'
  readonly module: Readonly<Record<string, unknown>>
  readonly output: string
}

export const TARGETS: readonly Target[] = [
  { name: 'server', module: serverSchema, output: 'apps/server/src/migrations/pg/schema.ts' },
  { name: 'sync', module: syncSchema, output: 'packages/sync/src/adapters/pg/schema.ts' },
]

/** The identity package's SQLite tables: the server schema re-exports them, and so does its twin. */
export const isIdentityTable = (sqlName: string): boolean => sqlName.startsWith('identity_')

/** The SQLite tables of a module that get a generated twin, by export name, in export order. */
export function generatedTables(
  module: Readonly<Record<string, unknown>>,
): [string, SQLiteTable][] {
  return Object.entries(module).filter(
    (entry): entry is [string, SQLiteTable] =>
      is(entry[1], SQLiteTable) && !isIdentityTable(getTableConfig(entry[1]).name),
  )
}

const dialect = new SQLiteDialect()

/** A SQL fragment of the SQLite schema as text, columns unquoted-table, as the DDL writes it. */
export function sqliteSqlText(fragment: SQL): string {
  const query = dialect.sqlToQuery(fragment, 'indexes')
  if (query.params.length > 0) {
    throw new Error(`a schema fragment binds values, which DDL cannot: ${query.sql}`)
  }
  return query.sql
}

/** `text` as the body of a TypeScript template literal. */
const templateBody = (text: string): string =>
  text.replaceAll('\\', '\\\\').replaceAll('`', '\\`').replaceAll('${', '\\${')

const sqlLiteral = (value: string): string => `'${value.replaceAll("'", "''")}'`
const tsString = (value: string): string =>
  `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`
const sqlTag = (text: string): string => `sql\`${templateBody(text)}\``

/** The Postgres class a text column gets: its declared class, unless an override keeps a timestamp as text. */
export function pgTextClass(table: string, column: string): TextColumnClass {
  const declared = textColumnClass(table, column)
  if (declared === undefined) {
    throw new Error(
      `${table}.${column} is a text column with no class: add it to ` +
        'apps/server/src/migrations/pg/schema-classes.ts (timestamp, json or text)',
    )
  }
  if (declared === 'timestamp' && `${table}.${column}` in PG_TIMESTAMP_COLUMNS_KEPT_AS_TEXT) {
    return 'text'
  }
  return declared
}

/** What one generated file imports. */
interface Uses {
  readonly core: Set<string>
  readonly columns: Set<string>
  sql: boolean
}

/** A column's Postgres builder expression, without its modifiers. */
function columnBuilder(table: string, column: Column, uses: Uses): { expr: string; kind: string } {
  const name = tsString(column.name)
  switch (column.columnType) {
    case 'SQLiteText':
    case 'SQLiteTextJson': {
      const kind = pgTextClass(table, column.name)
      if (column.columnType === 'SQLiteTextJson' && kind !== 'json') {
        throw new Error(`${table}.${column.name} is mode: 'json' on SQLite but not classed json`)
      }
      const builder =
        kind === 'timestamp'
          ? 'isoTimestamp'
          : kind === 'json'
            ? column.columnType === 'SQLiteTextJson'
              ? 'jsonValue'
              : 'jsonText'
            : 'textC'
      uses.columns.add(builder)
      return { expr: `${builder}(${name})`, kind }
    }
    case 'SQLiteInteger':
      uses.columns.add('int8')
      return { expr: `int8(${name})`, kind: 'integer' }
    case 'SQLiteBoolean':
      uses.core.add('boolean')
      return { expr: `boolean(${name})`, kind: 'boolean' }
    case 'SQLiteReal':
      uses.core.add('doublePrecision')
      return { expr: `doublePrecision(${name})`, kind: 'real' }
    case 'SQLiteBlob':
    case 'SQLiteBlobBuffer':
      uses.core.add('bytea')
      return { expr: `bytea(${name})`, kind: 'blob' }
    default:
      throw new Error(
        `${table}.${column.name}: no Postgres mapping for the SQLite column type ${column.columnType}`,
      )
  }
}

/** The `.default(…)` a column gets on Postgres, or '' for none. */
function defaultOf(table: string, column: Column, kind: string, uses: Uses): string {
  const override = PG_DEFAULT_OVERRIDES[`${table}.${column.name}`]
  if (override !== undefined) {
    uses.sql = true
    return `.default(${sqlTag(override.sql)})`
  }
  if (!column.hasDefault || column.default === undefined) return ''
  const value = column.default
  if (kind === 'boolean') {
    const text = is(value, SQL) ? sqliteSqlText(value).trim().toLowerCase() : String(value)
    if (text === '0' || text === 'false') return '.default(false)'
    if (text === '1' || text === 'true') return '.default(true)'
    throw new Error(`${table}.${column.name}: a boolean default of ${text}`)
  }
  if (is(value, SQL)) {
    throw new Error(
      `${table}.${column.name}: a SQL default (${sqliteSqlText(value)}) needs a Postgres form ` +
        'in PG_DEFAULT_OVERRIDES',
    )
  }
  if (kind === 'integer' || kind === 'real') {
    if (typeof value !== 'number') throw new Error(`${table}.${column.name}: default ${value}`)
    return `.default(${value})`
  }
  // A custom type's default is written as a SQL literal: drizzle-kit renders a plain
  // string default on a custom type unquoted, and a JSON one double-encoded.
  const text = typeof value === 'string' ? value : JSON.stringify(value)
  if (kind === 'timestamp' && text === '') {
    throw new Error(
      `${table}.${column.name}: a timestamp column defaulting to '' needs '-infinity' in PG_DEFAULT_OVERRIDES`,
    )
  }
  uses.sql = true
  return `.default(${sqlTag(sqlLiteral(text))})`
}

/** The Postgres source of one table. */
function tableSource(
  exportName: string,
  table: SQLiteTable,
  exportOf: ReadonlyMap<SQLiteTable, string>,
  uses: Uses,
): string {
  const config = getTableConfig(table)
  const name = config.name
  const keyOf = new Map<Column, string>(
    Object.entries(getTableColumns(table)).map(([key, column]) => [column as Column, key]),
  )
  const columnRef = (column: Column): string => {
    const key = keyOf.get(column)
    if (key === undefined) throw new Error(`${name}: a constraint names a column of another table`)
    return `table.${key}`
  }
  const lines: string[] = []
  for (const column of config.columns) {
    const key = keyOf.get(column)
    if (key === undefined) throw new Error(`${name}.${column.name}: no property key`)
    const { expr, kind } = columnBuilder(name, column, uses)
    let source = expr
    if (column.primary) {
      source += '.primaryKey()'
      if (kind === 'integer') source += '.generatedByDefaultAsIdentity()'
    } else if (column.notNull) source += '.notNull()'
    source += defaultOf(name, column, kind, uses)
    if (column.isUnique) {
      source +=
        column.uniqueName === undefined ? '.unique()' : `.unique(${tsString(column.uniqueName)})`
    }
    source += `.$type<SqliteRow<'${exportName}'>['${key}']>()`
    lines.push(`    ${key}: ${source},`)
  }

  const extras: string[] = []
  for (const pk of config.primaryKeys) {
    uses.core.add('primaryKey')
    const named = pk.name === undefined ? '' : `name: ${tsString(pk.name)}, `
    extras.push(`primaryKey({ ${named}columns: [${pk.columns.map(columnRef).join(', ')}] })`)
  }
  for (const constraint of config.uniqueConstraints) {
    uses.core.add('unique')
    extras.push(
      `unique(${tsString(constraint.getName())}).on(${constraint.columns.map(columnRef).join(', ')})`,
    )
  }
  for (const index of config.indexes) {
    const builder = index.config.unique ? 'uniqueIndex' : 'index'
    uses.core.add(builder)
    const parts = index.config.columns.map((part) => {
      if (is(part, SQL)) {
        uses.sql = true
        return sqlTag(sqliteSqlText(part))
      }
      return columnRef(part as Column)
    })
    let source = `${builder}(${tsString(index.config.name)}).on(${parts.join(', ')})`
    const override = PG_INDEX_WHERE_OVERRIDES[`${name}.${index.config.name}`]
    if (override !== undefined) {
      uses.sql = true
      source += `.where(${sqlTag(override.sql)})`
    } else if (index.config.where !== undefined) {
      uses.sql = true
      source += `.where(${sqlTag(sqliteSqlText(index.config.where))})`
    }
    extras.push(source)
  }
  // Indexes only the Postgres twin has (search's GIN index), in key order.
  for (const [key, only] of Object.entries(PG_ONLY_INDEXES).sort(([a], [b]) =>
    a.localeCompare(b),
  )) {
    const [table, index] = key.split('.') as [string, string]
    if (table !== name) continue
    uses.core.add('index')
    uses.sql = true
    extras.push(`index(${tsString(index)}).using('${only.using}', ${sqlTag(only.sql)})`)
  }
  for (const fk of config.foreignKeys) {
    uses.core.add('foreignKey')
    const reference = fk.reference()
    const target = exportOf.get(reference.foreignTable as SQLiteTable)
    if (target === undefined) {
      throw new Error(`${name}: a foreign key to a table outside this schema module`)
    }
    const foreignKeyOf = new Map<Column, string>(
      Object.entries(getTableColumns(reference.foreignTable)).map(([key, column]) => [
        column as Column,
        key,
      ]),
    )
    const foreign = reference.foreignColumns.map((column) => {
      const key = foreignKeyOf.get(column as Column)
      if (key === undefined) throw new Error(`${name}: a foreign key to an unknown column`)
      // A reference to this same table goes through `table`: naming the table being
      // defined in its own initializer makes TypeScript type it `any`.
      return `${reference.foreignTable === table ? 'table' : target}.${key}`
    })
    const fkName = PG_FOREIGN_KEY_RENAMES[`${name}.${fk.getName()}`]?.name ?? fk.getName()
    let source =
      `foreignKey({ name: ${tsString(fkName)}, ` +
      `columns: [${reference.columns.map((column) => columnRef(column as Column)).join(', ')}], ` +
      `foreignColumns: [${foreign.join(', ')}] })`
    if (fk.onDelete !== undefined) source += `.onDelete('${fk.onDelete}')`
    if (fk.onUpdate !== undefined) source += `.onUpdate('${fk.onUpdate}')`
    extras.push(source)
  }
  for (const constraint of config.checks) {
    uses.core.add('check')
    uses.sql = true
    const override = PG_CHECK_OVERRIDES[`${name}.${constraint.name}`]
    const text = override?.sql ?? sqliteSqlText(constraint.value)
    extras.push(`check(${tsString(constraint.name)}, ${sqlTag(text)})`)
  }

  const head = `export const ${exportName} = pgTable(\n  ${tsString(name)},\n  {\n${lines.join('\n')}\n  }`
  if (extras.length === 0) return `${head},\n)\n`
  const parameter = extras.some((extra) => extra.includes('table.')) ? 'table' : '_table'
  return `${head},\n  (${parameter}) => [\n${extras.map((extra) => `    ${extra},`).join('\n')}\n  ],\n)\n`
}

const MAPPING_TABLE = ` * | column class (SQLite)                 | Postgres                      | Drizzle here       |
 * |--------------------------------------|-------------------------------|--------------------|
 * | ISO timestamp text (class timestamp) | \`timestamptz(3)\`              | \`isoTimestamp\`     |
 * | JSON text (class json)               | \`json\`                        | \`jsonText\`         |
 * | JSON, \`mode: 'json'\`                 | \`json\`                        | \`jsonValue\`        |
 * | other text (class text)              | \`text COLLATE "C"\`            | \`textC\`            |
 * | integer                              | \`bigint\`                      | \`int8\`             |
 * | integer one-column primary key       | \`bigint\` identity, by default | \`int8\` + identity  |
 * | integer, \`mode: 'boolean'\`           | \`boolean\`                     | \`boolean\`          |
 * | real                                 | \`double precision\`            | \`doublePrecision\`  |`

function serverHeader(): string {
  return `/**
 * THE SERVER SCHEMA ON POSTGRES [POD-6978, POD-6958 design 2.2, 2.3].
 *
 * The twin of \`../schema.ts\`, table for table, under the same export names, so the
 * store's binding (\`store/executor/binding.ts\`) hands a query definition these tables
 * as its \`t\` on Postgres and the same definition source builds native Postgres SQL.
 *
 * GENERATED ONCE by \`scripts/generate-pg-schema.ts\`, then kept as source. A schema
 * change edits \`../schema.ts\` and then reruns \`bun run schema:pg\` or edits this file by
 * hand; \`schema-parity.test.ts\` (structure and Postgres types) and
 * \`schema-parity.type-test.ts\` (row types) fail until the two agree. A deliberate
 * difference goes in \`schema-overrides.ts\`, with its reason, which the generator keeps.
 *
 * The native types of design 2.3 (operator decision OD5); the column classes are declared
 * in \`schema-classes.ts\`:
 *
${MAPPING_TABLE}
 *
 * Every column's TypeScript type is its SQLite twin's, by reference
 * (\`$type<SqliteRow<'table'>['column']>()\`), so a brand or a value union cannot drift; the
 * Postgres driver (\`store/executor/pg-types.ts\`) makes the values match at run time.
 * The column types are the sync package's, shared by both twins.
 */

`
}

function syncHeader(): string {
  return `/**
 * THE SYNC TABLES ON POSTGRES, AND THE TWINS' COLUMN TYPES [POD-6978, POD-6958 design 2.2, 2.3].
 *
 * The twin of \`../sqlite/schema.ts\`, under the same export names, and
 * {@link pgSyncTables}, the twin of \`sqliteSyncTables\`: what a Postgres store binds as
 * the sync adapter's tables.
 *
 * GENERATED ONCE by \`scripts/generate-pg-schema.ts\`, then kept as source (the tables
 * below the column types); the server's \`migrations/pg/schema-parity.test.ts\` holds the
 * two schemas to the same structure, and its type test to the same row types.
 *
 * THE COLUMN TYPES (design 2.3) are declared here because both twins use them and this
 * package cannot import the server:
 *
${MAPPING_TABLE}
 *
 * Neither JSON type is drizzle's \`json()\`/\`jsonb()\`, which would encode a string value a
 * second time; the Postgres driver reads \`json\` as its raw text, so \`jsonText\` passes it
 * through and \`jsonValue\` parses it, as SQLite's \`mode: 'json'\` does.
 */

`
}

const COLUMN_TYPES = `/** Text in byte order (\`COLLATE "C"\`), as SQLite compares text. Drizzle's \`text()\` has no collation. */
export const textC = customType<{ data: string; driverData: string }>({
  dataType: () => 'text COLLATE "C"',
})

/** JSON kept as its exact text, both ways. */
export const jsonText = customType<{ data: string; driverData: string }>({
  dataType: () => 'json',
})

/** JSON parsed on read and stringified on write: SQLite's \`text({ mode: 'json' })\`. */
export const jsonValue = customType<{ data: unknown; driverData: string }>({
  dataType: () => 'json',
  toDriver: (value) => JSON.stringify(value),
  fromDriver: (value) => JSON.parse(value) as unknown,
})

/** An ISO timestamp: \`timestamptz(3)\`, read and written as \`toISOString()\` text. */
export const isoTimestamp = (name: string) =>
  timestamp(name, { withTimezone: true, precision: 3, mode: 'string' })

/** An integer: \`bigint\`, read as a number (the driver refuses values beyond 2^53). */
export const int8 = (name: string) => bigint(name, { mode: 'number' })

`

/** The re-export of the tables only the Postgres schema has (`PG_ONLY_TABLES`), or ''. */
function pgOnlyTablesExport(): string {
  const keys = Object.keys(PG_ONLY_TABLES).sort()
  if (keys.length === 0) return ''
  return (
    '/** Tables only the Postgres schema has: see `PG_ONLY_TABLES` in `schema-overrides.ts`. */\n' +
    `export { ${keys.join(', ')} } from './pg-only-tables'\n\n`
  )
}

/** The whole generated file of one target. */
export function generate(target: Target): string {
  const tables = generatedTables(target.module)
  const exportOf = new Map(tables.map(([key, table]) => [table, key]))
  const uses: Uses = { core: new Set(['pgTable']), columns: new Set(), sql: false }
  const bodies = tables.map(([key, table]) => tableSource(key, table, exportOf, uses))
  const sqliteImport = target.name === 'server' ? '../schema' : '../sqlite/schema'
  const rowType =
    `/** The SQLite row of the twin table, whose column types every twin column takes. */\n` +
    `type SqliteRow<T extends keyof typeof sqlite> = (typeof sqlite)[T] extends {\n` +
    `  readonly $inferSelect: infer Row\n} ? Row : never\n\n`
  const sql = uses.sql ? `import { sql } from 'drizzle-orm'\n` : ''
  if (target.name === 'sync') {
    const core = [...uses.core, 'bigint', 'customType', 'timestamp'].sort()
    const set = tables.map(([key]) => `  ${key},`).join('\n')
    return (
      syncHeader() +
      sql +
      `import { ${core.join(', ')} } from 'drizzle-orm/pg-core'\n` +
      `import type * as sqlite from '${sqliteImport}'\n\n` +
      COLUMN_TYPES +
      rowType +
      bodies.join('\n') +
      `\n/** The sync adapter's tables on Postgres: the twin of \`sqliteSyncTables\`. */\n` +
      `export const pgSyncTables = Object.freeze({\n${set}\n})\n`
    )
  }
  const core = [...uses.core].sort()
  const columns = [...uses.columns].sort()
  return (
    serverHeader() +
    `/**\n * THE IDENTITY TABLES are the identity package's Postgres schema, re-exported as \`../schema.ts\`\n` +
    ` * re-exports its SQLite one. The package owns both twins and runs one suite on both\n` +
    ` * (\`packages/identity/src/testing\`); the library tables keep the names the cloud already has,\n` +
    ` * exported here under the server schema's names.\n */\n` +
    `export {\n  account as identityAccount,\n  identityInvitation,\n  identityMembership,\n` +
    `  identityMembershipEvent,\n  identityOneTimeCode,\n  identityWorkspaceRevision,\n` +
    `  rateLimit as identityRateLimit,\n  session as identitySession,\n  user as identityUser,\n` +
    `  verification as identityVerification,\n} from '@podium/identity/schema/pg'\n\n` +
    pgOnlyTablesExport() +
    sql +
    `import { ${core.join(', ')} } from 'drizzle-orm/pg-core'\n` +
    `import { ${columns.join(', ')} } from '../../../../../packages/sync/src/adapters/pg/schema'\n` +
    `import type * as sqlite from '${sqliteImport}'\n\n` +
    rowType +
    bodies.join('\n')
  )
}

/** One table's generated source, from a whole generated file. */
export function tableBlock(source: string, exportName: string): string | undefined {
  const start = source.indexOf(`export const ${exportName} = pgTable(`)
  if (start < 0) return undefined
  const next = source.indexOf('\nexport const ', start + 1)
  return source.slice(start, next < 0 ? undefined : next + 1).trimEnd()
}

function formatted(path: string): void {
  const result = Bun.spawnSync(['bunx', 'biome', 'check', '--write', path], { cwd: ROOT })
  if (result.exitCode !== 0) {
    throw new Error(
      `biome refused ${path}:\n${result.stdout.toString()}${result.stderr.toString()}`,
    )
  }
}

function main(argv: readonly string[]): number {
  const check = argv.includes('--check')
  const only = argv.filter((arg) => !arg.startsWith('--'))
  if (!check) {
    for (const target of TARGETS) {
      const path = join(ROOT, target.output)
      writeFileSync(path, generate(target))
      formatted(target.output)
      console.log(`wrote ${target.output}`)
    }
    return 0
  }
  // --check: generate into a scratch copy, format it the same way, compare table blocks.
  let differing = 0
  for (const target of TARGETS) {
    const scratch = join(ROOT, `${target.output}.check.ts`)
    writeFileSync(scratch, generate(target))
    try {
      formatted(`${target.output}.check.ts`)
      const fresh = readFileSync(scratch, 'utf8')
      const committed = readFileSync(join(ROOT, target.output), 'utf8')
      for (const [key, table] of generatedTables(target.module)) {
        const sqlName = getTableConfig(table).name
        if (only.length > 0 && !only.includes(sqlName) && !only.includes(key)) continue
        const wanted = tableBlock(fresh, key)
        const have = tableBlock(committed, key)
        if (only.length > 0) console.log(wanted)
        if (wanted !== have) {
          differing += 1
          console.log(
            `${target.output}: ${key} (${sqlName}) differs from what the generator writes`,
          )
        }
      }
    } finally {
      Bun.spawnSync(['rm', '-f', scratch])
    }
  }
  if (differing === 0) console.log('every checked table is what the generator writes')
  return differing === 0 ? 0 : 1
}

if (import.meta.main) process.exit(main(process.argv.slice(2)))
