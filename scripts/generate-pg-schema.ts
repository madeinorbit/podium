/**
 * GENERATE THE POSTGRES SCHEMA TWINS FROM THE SQLITE SCHEMAS [POD-6978, POD-6958 design 2.2].
 *
 *   bun run schema:pg                    write both twins
 *   bun run schema:pg -- --check         say which tables differ from what the generator writes
 *   bun run schema:pg -- --check <table> print what the generator writes for that table
 *
 * It reads every SQLite table with drizzle's `getTableConfig()` and writes its Postgres
 * twin by the native type mapping of design 2.3 (operator decision OD5):
 *
 * | SQLite                                   | Postgres                                    |
 * |------------------------------------------|---------------------------------------------|
 * | text, class `timestamp`                  | `timestamptz(3)`, `mode: 'string'`           |
 * | text, class `json`                       | `json` (`jsonText`; `jsonValue` for `mode: 'json'`) |
 * | text, class `text`                       | `text COLLATE "C"` (`textC`)                 |
 * | integer                                  | `bigint`, `mode: 'number'`                   |
 * | integer, the table's one-column key      | `bigint generated by default as identity`   |
 * | integer, `mode: 'boolean'`               | `boolean`                                   |
 * | real                                     | `double precision`                          |
 * | blob                                     | `bytea`                                     |
 *
 * Text columns take their class from `apps/server/src/migrations/pg/schema-classes.ts`
 * (SQLite records no timestamp or JSON type); a text column it does not name stops the
 * generator. Deliberate differences come from `schema-overrides.ts`. Every column's
 * TypeScript type is its SQLite twin's, by reference (`$type<SqliteRow<'t'>['c']>()`), so
 * the brands, value unions and JSON shapes cannot drift; the type-level parity test
 * checks the rest (nullability, insert optionality, the column set).
 *
 * Two outputs, same rules:
 *   apps/server/src/migrations/schema.ts        → apps/server/src/migrations/pg/schema.ts
 *   packages/sync/src/adapters/sqlite/schema.ts → packages/sync/src/adapters/pg/schema.ts
 * The identity tables are not generated: the identity package owns both of their schemas,
 * and the server's Postgres schema re-exports its Postgres one.
 *
 * A HELPER, NOT A BUILD STEP. After the first run both files are source. A schema change
 * edits the SQLite file and then either reruns this or edits the Postgres file by hand;
 * `schema-parity.test.ts` fails until the two agree. Rerunning rewrites the whole file, so
 * a hand difference belongs in the overrides, where the generator keeps it.
 */

