#!/bin/sh
# Replace a stranded installed bundle from an artifact trio copied onto the host.
# This deliberately does not contact Podium or restart any service.
set -eu

usage() {
  cat >&2 <<'EOF'
Usage: repair-stranded-update.sh --artifact PATH [--instance ID]
       [--state-dir PATH] [--install-dir PATH]

The artifact's .sig and .meta.json sidecars must be beside it. The script reads
the paired instance key from STATE_DIR/daemon.json, verifies all three files
without invoking the installed updater, swaps the bundle, and retains
INSTALL_DIR.old for host-local rollback. It never downloads or restarts Podium.
EOF
  exit 2
}

fail() {
  printf 'podium repair: %s\n' "$1" >&2
  exit 1
}

INSTANCE=default
ARTIFACT=
STATE_DIR=
INSTALL_DIR=

while [ "$#" -gt 0 ]; do
  case "$1" in
    --artifact)
      [ "$#" -ge 2 ] || usage
      ARTIFACT=$2
      shift 2
      ;;
    --instance)
      [ "$#" -ge 2 ] || usage
      INSTANCE=$2
      shift 2
      ;;
    --state-dir)
      [ "$#" -ge 2 ] || usage
      STATE_DIR=$2
      shift 2
      ;;
    --install-dir)
      [ "$#" -ge 2 ] || usage
      INSTALL_DIR=$2
      shift 2
      ;;
    -h|--help) usage ;;
    *) usage ;;
  esac
done

[ -n "$ARTIFACT" ] || usage
case "$INSTANCE" in
  ''|[!a-z]*|*[!a-z0-9-]*) fail "invalid instance id '$INSTANCE'" ;;
esac
[ "${#INSTANCE}" -le 32 ] || fail "invalid instance id '$INSTANCE'"

ACCOUNT_HOME=${HOME:?HOME is required}
if [ -z "$STATE_DIR" ]; then
  if [ "$INSTANCE" = default ]; then
    STATE_DIR=$ACCOUNT_HOME/.podium
  else
    STATE_DIR=${XDG_STATE_HOME:-$ACCOUNT_HOME/.local/state}/podium/$INSTANCE
  fi
fi
if [ -z "$INSTALL_DIR" ]; then
  DATA_HOME=${XDG_DATA_HOME:-$ACCOUNT_HOME/.local/share}
  if [ "$INSTANCE" = default ]; then
    INSTALL_DIR=$DATA_HOME/podium
  else
    INSTALL_DIR=$DATA_HOME/podium-instances/$INSTANCE
  fi
fi

case "$STATE_DIR" in /*) ;; *) fail 'state directory must be an absolute path' ;; esac
case "$INSTALL_DIR" in
  /|'') fail 'refusing unsafe install directory' ;;
  /*) ;;
  *) fail 'install directory must be an absolute path' ;;
esac

for tool in base64 dirname grep mkdir mktemp mv openssl rm sed tar tr uname wc; do
  command -v "$tool" >/dev/null 2>&1 || fail "required tool '$tool' is unavailable"
done

SIGNATURE=$ARTIFACT.sig
METADATA=$ARTIFACT.meta.json
IDENTITY=$STATE_DIR/daemon.json
for required in "$ARTIFACT" "$SIGNATURE" "$METADATA" "$IDENTITY"; do
  [ -f "$required" ] && [ -r "$required" ] || fail "required file is unreadable: $required"
done
[ -d "$INSTALL_DIR" ] || fail "installed bundle is missing: $INSTALL_DIR"
[ -x "$INSTALL_DIR/podium" ] || fail "installed bundle has no executable podium binary"
[ -f "$INSTALL_DIR/VERSION" ] || fail "installed bundle has no VERSION file"
[ ! -e "$INSTALL_DIR.old" ] && [ ! -L "$INSTALL_DIR.old" ] ||
  fail "rollback bundle already exists at $INSTALL_DIR.old; preserve it before repairing"

# These files are generated by Podium and each queried field is unique. Flattening
# lets this POSIX recovery script avoid depending on Bun, jq, or the broken binary.
json_string() {
  JSON_FILE=$1
  JSON_KEY=$2
  JSON_VALUE=$(tr -d '\n\r' < "$JSON_FILE" | sed -n \
    "s/.*\"$JSON_KEY\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p")
  [ -n "$JSON_VALUE" ] || fail "$JSON_FILE has no string field '$JSON_KEY'"
  printf '%s\n' "$JSON_VALUE"
}

json_number() {
  JSON_FILE=$1
  JSON_KEY=$2
  JSON_VALUE=$(tr -d '\n\r' < "$JSON_FILE" | sed -n \
    "s/.*\"$JSON_KEY\"[[:space:]]*:[[:space:]]*\([0-9][0-9]*\).*/\1/p")
  [ -n "$JSON_VALUE" ] || fail "$JSON_FILE has no numeric field '$JSON_KEY'"
  printf '%s\n' "$JSON_VALUE"
}

VERSION=$(json_string "$METADATA" version)
PLATFORM=$(json_string "$METADATA" platform)
EXPECTED_DIGEST=$(json_string "$METADATA" digest)
EXPECTED_SIZE=$(json_number "$METADATA" size)
EXPECTED_FINGERPRINT=$(json_string "$METADATA" keyFingerprint)
PINNED_PUBKEY=$(json_string "$IDENTITY" updatePubkey)

printf '%s\n' "$VERSION" | grep -Eq \
  '^[0-9]+\.[0-9]+\.[0-9]+([-.+][0-9A-Za-z]+)*$' ||
  fail "metadata version '$VERSION' is not an orderable published version"
case "$VERSION" in dev|dev+*) fail "refusing unordered source version '$VERSION'" ;; esac

case "$(uname -s)/$(uname -m)" in
  Linux/x86_64|Linux/amd64) HOST_PLATFORM=linux-x86_64 ;;
  Linux/aarch64|Linux/arm64) HOST_PLATFORM=linux-aarch64 ;;
  *) fail "unsupported repair host $(uname -s)/$(uname -m)" ;;
esac
[ "$PLATFORM" = "$HOST_PLATFORM" ] ||
  fail "artifact platform is $PLATFORM, but this host is $HOST_PLATFORM"

ACTUAL_SIZE=$(wc -c < "$ARTIFACT" | tr -d '[:space:]')
[ "$ACTUAL_SIZE" = "$EXPECTED_SIZE" ] ||
  fail "artifact size verification FAILED (expected $EXPECTED_SIZE, got $ACTUAL_SIZE)"
ACTUAL_DIGEST=sha256-$(openssl dgst -sha256 -binary "$ARTIFACT" | base64 | tr -d '\n\r')
[ "$ACTUAL_DIGEST" = "$EXPECTED_DIGEST" ] ||
  fail 'artifact digest verification FAILED; nothing was changed'

umask 077
STAGE_ROOT=$(mktemp -d "$(dirname "$INSTALL_DIR")/.podium-stranded-repair.XXXXXX")
cleanup() {
  [ -z "${STAGE_ROOT:-}" ] || rm -rf "$STAGE_ROOT"
}
trap cleanup EXIT HUP INT TERM

printf '%s' "$PINNED_PUBKEY" | base64 -d > "$STAGE_ROOT/pub.der" 2>/dev/null ||
  fail 'daemon.json updatePubkey is not valid base64'
PIN_HASH=$(openssl dgst -sha256 -binary "$STAGE_ROOT/pub.der" | base64 | tr -d '\n\r')
case "$EXPECTED_FINGERPRINT" in
  sha256-*) META_PIN_HASH=${EXPECTED_FINGERPRINT#sha256-} ;;
  SHA256:*) META_PIN_HASH=${EXPECTED_FINGERPRINT#SHA256:} ;;
  *) fail "unsupported metadata key fingerprint '$EXPECTED_FINGERPRINT'" ;;
esac
[ "$PIN_HASH" = "$META_PIN_HASH" ] ||
  fail 'wrong key: artifact metadata fingerprint does not match daemon.json updatePubkey'

tr -d '[:space:]' < "$SIGNATURE" | base64 -d > "$STAGE_ROOT/signature.raw" 2>/dev/null ||
  fail 'artifact signature is not valid base64'
if ! openssl pkeyutl -verify -pubin -inkey "$STAGE_ROOT/pub.der" -keyform DER -rawin \
  -in "$ARTIFACT" -sigfile "$STAGE_ROOT/signature.raw" >/dev/null 2>&1; then
  fail 'signature verification FAILED against the pinned instance key; nothing was changed'
fi

tar -tzf "$ARTIFACT" > "$STAGE_ROOT/archive-entries"
[ -s "$STAGE_ROOT/archive-entries" ] || fail 'artifact archive is empty'
while IFS= read -r entry; do
  case "$entry" in headless|headless/|headless/*) ;; *) fail "unsafe archive entry: $entry" ;; esac
  case "/$entry/" in *'/../'*|*'/./'*) fail "unsafe archive entry: $entry" ;; esac
done < "$STAGE_ROOT/archive-entries"

mkdir "$STAGE_ROOT/extracted"
tar --no-same-owner --no-same-permissions -xzf "$ARTIFACT" -C "$STAGE_ROOT/extracted"
REPLACEMENT=$STAGE_ROOT/extracted/headless
[ -d "$REPLACEMENT" ] || fail 'artifact has no headless bundle'
[ -f "$REPLACEMENT/podium" ] && [ ! -L "$REPLACEMENT/podium" ] &&
  [ -x "$REPLACEMENT/podium" ] || fail 'artifact has no regular executable podium binary'
[ -f "$REPLACEMENT/VERSION" ] && [ ! -L "$REPLACEMENT/VERSION" ] ||
  fail 'artifact has no regular VERSION file'
STAGED_VERSION=$(tr -d '\n\r' < "$REPLACEMENT/VERSION")
[ "$STAGED_VERSION" = "$VERSION" ] ||
  fail "artifact VERSION is '$STAGED_VERSION', metadata says '$VERSION'"

mv "$INSTALL_DIR" "$INSTALL_DIR.old"
if ! mv "$REPLACEMENT" "$INSTALL_DIR"; then
  mv "$INSTALL_DIR.old" "$INSTALL_DIR"
  fail 'could not promote the staged bundle; the previous install was restored'
fi

printf 'podium repair: installed %s at %s\n' "$VERSION" "$INSTALL_DIR"
printf 'podium repair: retained the previous bundle at %s.old\n' "$INSTALL_DIR"
printf 'podium repair: no service was stopped or restarted; continue the host-local runbook\n'
