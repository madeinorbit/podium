import { chromium } from 'playwright';
import fs from 'fs';
const b = await chromium.launch({ headless: true, args:['--no-sandbox','--js-flags=--max-old-space-size=4096'] });
const ctx = await b.newContext({ viewport:{width:1440,height:900} });
await ctx.addCookies([{name:'podium_session',value:process.env.PODIUM_COOKIE,domain:'127.0.0.1',path:'/'}]);
const page = await ctx.newPage();
page.on('crash',()=>console.log('PAGE CRASH'));
page.on('console',m=>{if(m.type()==='error')console.log('CERR',m.text().slice(0,150));});
const cdp = await ctx.newCDPSession(page);
await cdp.send('Profiler.enable');
await cdp.send('Profiler.setSamplingInterval',{interval:1000});
await cdp.send('Profiler.start');
console.log('profiler started');
page.goto('http://127.0.0.1:18787/',{waitUntil:'domcontentloaded',timeout:60000}).catch(e=>console.log('goto',e.message.slice(0,60)));
const SECS=Number(process.argv[2]||120);
await new Promise(r=>setTimeout(r,SECS*1000));
console.log('stopping profiler');
const {profile} = await cdp.send('Profiler.stop');
fs.writeFileSync('cdp.cpuprofile', JSON.stringify(profile));
console.log('samples', profile.samples.length, 'nodes', profile.nodes.length);
await b.close().catch(()=>{});
