/**
 * POD-4574 (Mc2) — arm-initiated edits for the correctness gate.
 *
 * A phase-c arm owns its optimism: the user edit goes through the arm's
 * `write.edit`, which paints at once, logs under its own txId and sends
 * through the kernel. The L4b gate must drive generated edits the same way —
 * through the arm, not around it — or it tests the kernel's optimism instead
 * of the arm's (coordinator ruling on POD-4574).
 *
 * THE ADAPTER. `ArmEditAdapter` is built once per gate run and shared by the
 * runner and the arm:
 *
 * - `transport(ctx)` is the `WriteTransport` the arm sends through. `send`
 *   invokes the SAME runtime action the runner used before (`updateIssue` /
 *   `markIssueRead` on the engine snapshot), so the kernel mints the mutation
 *   id, persists and holds it at the scripted server exactly as today. The
 *   arm's txId and the kernel's id are paired later (see below): the arm logs
 *   under its own id, the kernel answers under its.
 * - `editHook` is the `editViaArm` the runner calls instead of the runtime
 *   action. It late-binds the CURRENT arm handle (a `refresh` disposes the
 *   arm and creates a new one over the new engine), so edits always go through
 *   the live arm.
 * - `pairFromStep` runs as the run's `onStep`: every edit step records both
 *   ids (`detail.armTxId` from the hook, `detail.mutationId` claimed from the
 *   outbox as today), and the adapter maps them both ways. Outcomes arriving
 *   under the kernel id are translated to the arm's before the arm sees them;
 *   `pending()` entries are translated the same way, so a re-created arm
 *   bootstraps the outbox under the arm ids it logged (W11).
 *
 * WHY TWO IDS. `edit()` must return its txId synchronously, before the kernel
 * has minted anything (write contract W2 discusses the arm-minted variant;
 * the gate keeps the kernel-minted path so the runner, the scripted server
 * and the drain model stay exactly as L4a proved them). The pairing is
 * unambiguous because steps apply one at a time with a settle between them.
 *
 * OWNERSHIP. Shared gate code (round three, POD-4545): the MobX gate uses it
 * now, the hand arm's Hc2 later. It imports the kernel's outbox entry type
 * and L3b's receipt mapping only.
 */

import type { OutboxEntry } from '@podium/client-core/outbox'
import { baseOf, subscribeReceipts } from '../receipts'
import type { ScenarioEngine } from '../scenarios'
import type {
  EditableStage,
  OutboxPendingWrite,
  TxId,
  WriteTransport,
} from '../write-contract'

/** Marked once a kernel outbox instance is watched (one wrap per instance). */
const WATCHED = Symbol.for('podium.gen.arm-edits.watched-retirements')

/**
 * Call `onRetire(kernelId)` after the kernel's ledger retires an awaiting
 * entry through this engine's outbox — including the wall-clock TTL prune,
 * which emits no outcome and would otherwise leave the arm showing a pending
 * overlay the oracle dropped. The call-through stays first: the kernel's
 * durable delete is unaffected, and observation never throws into it.
 */
function watchRetirements(ctx: ScenarioEngine, onRetire: (kernelId: string) => void): void {
  const outbox = ctx.engine.outbox as {
    retireAwaiting(mid: unknown): unknown
    [WATCHED]?: boolean
  }
  if (outbox[WATCHED] === true) return
  const previous = outbox.retireAwaiting.bind(outbox)
  outbox.retireAwaiting = (mid: unknown) => {
    const result = previous(mid)
    try {
      onRetire(mid as string)
    } catch {
      // Observation only: a gate hook must not break the kernel.
    }
    return result
  }
  outbox[WATCHED] = true
}

/** What the runner hands a generated edit to the arm (a mark-read's stamp is
 *  generated by the caller; the kernel stamps its own independently and the
 *  slice never compares the two). */
export type ArmEditPatch = { title: string } | { stage: EditableStage } | { readAt: string }

/** `GenRunOptions.editViaArm`: paint + log through the live arm, return its txId. */
export type ArmEditFn = (id: string, patch: ArmEditPatch) => TxId

export class ArmEditAdapter {
  private readonly armToKernel = new Map<string, string>()
  private readonly kernelToArm = new Map<string, string>()
  /** The live arm's write API, set by the gate's arm factory on every create. */
  currentEdit: ArmEditFn | null = null
  /**
   * Mirror one kernel-side retirement: called with the arm txId when the
   * kernel retires an entry the arm logged. Set alongside `currentEdit`.
   */
  currentExpire: ((armTx: TxId) => void) | null = null

  /** The hook the runner calls instead of the runtime action. */
  readonly editHook: ArmEditFn = (id, patch) => {
    const edit = this.currentEdit
    if (!edit) throw new Error('[arm-edits] no live arm for the generated edit')
    return edit(id, patch)
  }

  /** Map both ids from a settled edit step's detail (`armTxId`, `mutationId`). */
  pairFromStep(detail: Record<string, unknown>): void {
    const armTx = detail['armTxId']
    const kernelId = detail['mutationId']
    if (typeof armTx === 'string' && typeof kernelId === 'string') this.pair(armTx, kernelId)
    const armTxIds = detail['armTxIds']
    const kernelIds = detail['mutationIds']
    if (Array.isArray(armTxIds) && Array.isArray(kernelIds)) {
      for (let i = 0; i < Math.min(armTxIds.length, kernelIds.length); i += 1) {
        const a = armTxIds[i]
        const k = kernelIds[i]
        if (typeof a === 'string' && typeof k === 'string') this.pair(a, k)
      }
    }
  }

  pair(armTx: string, kernelId: string): void {
    this.armToKernel.set(armTx, kernelId)
    this.kernelToArm.set(kernelId, armTx)
  }

  toKernel(armTx: TxId): string | undefined {
    return this.armToKernel.get(armTx as string)
  }

  toArm(kernelId: string): TxId | undefined {
    return this.kernelToArm.get(kernelId) as TxId | undefined
  }

  /**
   * The `WriteTransport` the arm sends through on `ctx`'s engine. `send`
   * invokes the same runtime action the runner called before the adapter, so
   * queueing, the mark-read collapse and the scripted-server hold are
   * unchanged; `subscribe` translates outcome ids to arm ids (unknown ids
   * pass through — the arm's log treats them as no-ops); `pending` lists
   * queued then awaiting-truth entries under arm ids for bootstrap (W11).
   *
   * It also watches the kernel's retirement of awaiting entries
   * (`outbox.retireAwaiting`, the ledger's TTL/cover/baseline prune): that
   * path emits no outcome, so without this the oracle would drop a pending
   * overlay the arm keeps showing — nondeterministically, on the wall clock.
   * A retirement the arm already settled (a cover that arrived as an echo)
   * is a no-op there.
   */
  transport(ctx: ScenarioEngine): WriteTransport {
    const adapter = this
    watchRetirements(ctx, (kernelId) => {
      const armTx = adapter.kernelToArm.get(kernelId)
      if (armTx !== undefined) adapter.currentExpire?.(armTx as TxId)
    })
    return {
      send(_armTx, command) {
        const actions = ctx.engine.getSnapshot()
        if (command.kind === 'issueUpdate') {
          void actions.updateIssue(command.input.id, command.input.patch as never)
        } else {
          void actions.markIssueRead(command.input.id)
        }
      },
      subscribe(listener) {
        return subscribeReceipts(ctx.engine, (event) => {
          const armTx = adapter.kernelToArm.get(event.txId as string)
          listener({ ...event, txId: (armTx ?? event.txId) as TxId })
        })
      },
      pending() {
        const out: OutboxPendingWrite[] = []
        const push = (entry: OutboxEntry, acked: boolean): void => {
          const armTx =
            (adapter.kernelToArm.get(entry.mutationId as string) as TxId | undefined) ??
            (entry.mutationId as TxId)
          const base = baseOf(entry)
          out.push({
            txId: armTx,
            kind: entry.kind,
            input: entry.input,
            queuedAt: entry.queuedAt,
            acked,
            ...(base === undefined ? {} : { base }),
          })
        }
        for (const entry of ctx.engine.outbox.pending()) push(entry, false)
        for (const entry of ctx.engine.outbox.awaiting()) push(entry, true)
        return out
      },
    }
  }
}
