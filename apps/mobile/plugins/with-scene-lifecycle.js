const fs = require('fs')
const path = require('path')
const { IOSConfig, withAppDelegate, withInfoPlist, withXcodeProject } = require('expo/config-plugins')

/**
 * ADOPT THE UISCENE LIFE CYCLE, WHICH IOS 27 REQUIRES TO LAUNCH AT ALL.
 *
 * An app built against the iOS 27 SDK that still has no scene manifest is
 * killed by UIKit before any of our code runs: TestFlight build 1.0.0 (13),
 * built with Xcode 27, crashed on every launch on iOS 27.0.1 with
 * `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption` (SIGTRAP,
 * 0.35 s after launch). iOS 26 devices were unaffected, which is why it got
 * past the earlier builds.
 *
 * Expo 57.0.28 ships the runtime half (`ExpoAppSceneDelegate`,
 * `ExpoReactNativeFactoryProvider`), but the SDK 57 prebuild template still
 * generates the app-delegate-owned window. This plugin applies the SDK 58
 * template's shape so `expo prebuild` produces it: `apps/mobile/ios` is
 * gitignored, so a hand-edited AppDelegate is one `--clean` away from gone.
 * Delete this plugin when moving to SDK 58, whose template already does all
 * three steps.
 *
 *   1. Info.plist names a single-scene manifest pointing at `SceneDelegate`.
 *   2. AppDelegate stops creating the window and starting React Native; it
 *      conforms to `ExpoReactNativeFactoryProvider` so the scene delegate can
 *      start React Native into the scene's window instead.
 *   3. `SceneDelegate.swift` (a bare `ExpoAppSceneDelegate`) joins the target.
 *
 * The AppDelegate's existing Linking overrides stay: under scenes UIKit no
 * longer calls them, but `ExpoAppSceneDelegate` re-feeds URL and user-activity
 * events to them and de-duplicates the `RCTLinkingManager` notification.
 */

const MARKER = '// @podium scene-lifecycle'

const SCENE_DELEGATE_FILE = 'SceneDelegate.swift'

const SCENE_DELEGATE_SOURCE = `internal import Expo

${MARKER} — generated by plugins/with-scene-lifecycle.js.
@objc(SceneDelegate)
class SceneDelegate: ExpoAppSceneDelegate {
  // Extension point for config plugins.
}
`

const SCENE_MANIFEST = {
  UIApplicationSupportsMultipleScenes: false,
  UISceneConfigurations: {
    UIWindowSceneSessionRoleApplication: [
      {
        UISceneConfigurationName: 'Default Configuration',
        UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
      },
    ],
  },
}

const CLASS_DECLARATION = /^class AppDelegate: ExpoAppDelegate \{$/m

// The block the SDK 57 template uses to own the window. Under scenes the
// window belongs to the scene, so starting React Native here would render
// into a window no scene ever shows.
const WINDOW_BLOCK =
  /^[ \t]*#if os\(iOS\) \|\| os\(tvOS\)\n[ \t]*window = UIWindow\(frame: UIScreen\.main\.bounds\)\n[ \t]*factory\.startReactNative\([\s\S]*?\)\n[ \t]*#endif\n/m

/**
 * Rewrites the template AppDelegate to hand the window to `SceneDelegate`.
 * Idempotent through the marker, because prebuild re-runs over an existing
 * `ios/`. A missing anchor throws rather than passing the file through: a
 * silent no-op hands back the iOS 27 launch crash this plugin exists to fix.
 */
function adoptSceneLifecycle(appDelegate) {
  if (appDelegate.includes(MARKER)) return appDelegate
  if (!CLASS_DECLARATION.test(appDelegate)) {
    throw new Error(
      'with-scene-lifecycle: AppDelegate has no `class AppDelegate: ExpoAppDelegate {` declaration to extend.',
    )
  }
  if (!WINDOW_BLOCK.test(appDelegate)) {
    throw new Error(
      'with-scene-lifecycle: AppDelegate has no template window/startReactNative block to hand to SceneDelegate.',
    )
  }
  return appDelegate
    .replace(
      CLASS_DECLARATION,
      `${MARKER}: SceneDelegate owns the window; see plugins/with-scene-lifecycle.js.\nclass AppDelegate: ExpoAppDelegate, ExpoReactNativeFactoryProvider {`,
    )
    .replace(
      WINDOW_BLOCK,
      '    // The window is created and React Native is started by `SceneDelegate` under the\n' +
        '    // scene-based life cycle (required by the iOS 27 SDK).\n',
    )
}

function withScenePlist(config) {
  return withInfoPlist(config, (next) => {
    next.modResults.UIApplicationSceneManifest = SCENE_MANIFEST
    return next
  })
}

function withSceneAppDelegate(config) {
  return withAppDelegate(config, (next) => {
    if (next.modResults.language !== 'swift') {
      throw new Error(`with-scene-lifecycle: expected a Swift AppDelegate, got ${next.modResults.language}.`)
    }
    next.modResults.contents = adoptSceneLifecycle(next.modResults.contents)
    return next
  })
}

function withSceneDelegateFile(config) {
  return withXcodeProject(config, (next) => {
    const projectName = IOSConfig.XcodeUtils.getProjectName(next.modRequest.projectRoot)
    const target = path.join(next.modRequest.platformProjectRoot, projectName, SCENE_DELEGATE_FILE)
    fs.writeFileSync(target, SCENE_DELEGATE_SOURCE)

    const filepath = path.join(projectName, SCENE_DELEGATE_FILE)
    if (!next.modResults.hasFile(filepath)) {
      IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
        filepath,
        groupName: projectName,
        project: next.modResults,
      })
    }
    return next
  })
}

module.exports = function withSceneLifecycle(config) {
  return withSceneDelegateFile(withSceneAppDelegate(withScenePlist(config)))
}

module.exports.adoptSceneLifecycle = adoptSceneLifecycle
module.exports.SCENE_MANIFEST = SCENE_MANIFEST
