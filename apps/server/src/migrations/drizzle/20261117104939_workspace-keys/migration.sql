-- POD-7024 (POD-6959 design 2.2, 2.3 and 2.6 "U3", migration M2): THE WORKSPACE KEYS.
--
-- Every workspace table is rebuilt (CREATE __new_x, INSERT ... SELECT, DROP, RENAME, indexes)
-- so that its primary key, unique constraints and indexes lead with workspace_id, a foreign key
-- between two workspace tables is composite ((workspace_id, x) references (workspace_id, id)),
-- and workspace_id has no default. The seven AUTOINCREMENT tables keep `id` as their primary key
-- with UNIQUE (workspace_id, id) beside it. The column migration (POD-7012) already filled
-- workspace_id on every row, so no 'local' literal appears here.
--
-- Generated by `bun run migration:new workspace-keys`, then edited by hand:
--   * every INSERT copies rowid explicitly (`conversations_fts` is external content on
--     conversations.rowid, and several reads order by rowid); an INTEGER PRIMARY KEY table copies
--     it as its id;
--   * an AUTOINCREMENT table carries its sqlite_sequence counter over, so a number freed by a
--     delete of the newest rows is never handed out again (event cursors rest on that);
--   * sync_feed is rebuilt with workspace_id NOT NULL (drizzle-kit does not emit NOT NULL on a
--     primary-key column);
--   * the shipping guard triggers are dropped first and recreated last, with every lookup in
--     their bodies also matching the workspace of the row that fired them;
--   * `issues` and `workflow_runs` get a BEFORE DELETE trigger that clears the references the
--     old single-column keys cleared with ON DELETE SET NULL: a composite key would set
--     workspace_id to NULL too, which NOT NULL refuses;
--   * the legacy feed_identity singleton is dropped (design 2.1);
--   * the segment index of the runtime search keys (`transcript_fts_keys`, made when search is
--     on) is dropped, so the store makes it again with workspace_id first when the index opens.
--
-- The whole migration runs in the migrator's one transaction with foreign keys off (the boot
-- bracket, migrations/store-lifecycle.ts): it is atomic, and a crash in the middle leaves the
-- database as it was. The PRAGMA foreign_keys lines drizzle-kit writes are no-ops inside it.
-- The boot logs one progress line per rebuilt table (migrations/index.ts).
