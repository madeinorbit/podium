/**
 * THE CAPTURE ORACLE: TRIGGERS ON POSTGRES, IN TESTS ONLY (POD-6982, POD-6958 design 2.5).
 *
 * Production Postgres captures inside each write statement (`sync/capture-pg.ts`), which
 * catches only the writes that use it. A trigger catches every write, so in tests the
 * Postgres leg installs PL/pgSQL row triggers, generated from the same `RECORD_SOURCES`,
 * that write a SHADOW capture into `sync_capture_oracle`. After each transaction the
 * shadow rows and the write path's rows must be the same multiset; any difference fails
 * the test that caused it. The triggers are allowed here: the no-procedures rule protects
 * production portability, and nothing installs them outside a test.
 *
 * What the oracle checks: that every write reached its capture form (a plain statement
 * leaves shadow rows the write path lacks), that the forms capture what a row trigger
 * sees (old and new keys, changed flags, the rows a statement really touched) and that
 * the cascades the delete forms capture are the ones Postgres performs (its referential
 * actions fire the children's triggers). It shares the key encoding and the conditions
 * with the forms (`pgKey`, `pgCaptureWhen`), so whether the Postgres forms of the row
 * filters and derived values mean what the SQLite ones mean is the cross-engine corpus's
 * check (`sync/capture-pg.test.ts`), which compares Postgres with SQLite's own triggers.
 *
 * A transaction cannot end with shadow rows nobody compared: the shadow table carries the
 * same deferred foreign key to an always-empty guard as `sync_capture`, so its COMMIT fails.
 */

import type { CapturedRow } from '@podium/sync'
import { captureTable, pgCaptureWhen, pgKey, type RowRef, sourcesByTable } from '../sync/capture-pg'
import { RECORD_SOURCES, type RecordSources } from '../sync/record-sources'

/** The shadow capture table. */
export const ORACLE_TABLE = 'sync_capture_oracle'
const ORACLE_GUARD = 'sync_capture_oracle_guard'
const TRIGGER_PREFIX = 'sync_capture_oracle__'

const quote = (name: string): string => `"${name.replaceAll('"', '""')}"`
const literal = (value: string): string => `'${value.replaceAll("'", "''")}'`

const rowRef =
  (row: 'OLD' | 'NEW'): RowRef =>
  (column) =>
    `${row}.${quote(column)}`

/** The DDL that installs the oracle: its tables, then one function and trigger per (table, op). */
export function oracleStatements(sources: RecordSources = RECORD_SOURCES): string[] {
  const out = [
    `CREATE TABLE IF NOT EXISTS ${ORACLE_GUARD} (id bigint PRIMARY KEY)`,
    `CREATE TABLE IF NOT EXISTS ${ORACLE_TABLE} (
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      kind text NOT NULL, source bigint NOT NULL, op text NOT NULL,
      old_key text, new_key text,
      unchecked bigint NOT NULL DEFAULT 0
        REFERENCES ${ORACLE_GUARD} (id) DEFERRABLE INITIALLY DEFERRED
    )`,
  ]
  for (const [name, list] of sourcesByTable(sources)) {
    const table = captureTable(name)
    for (const [op, event] of [
      ['i', 'INSERT'],
      ['u', 'UPDATE'],
      ['d', 'DELETE'],
    ] as const) {
      const branches = list.filter(({ source }) => (source.ops ?? ['i', 'u', 'd']).includes(op))
      if (branches.length === 0) continue
      const fn = quote(`${TRIGGER_PREFIX}${name}__${op}`)
      const body = branches
        .map(({ kind, index, source }) => {
          const when = pgCaptureWhen(op, table, source, rowRef('OLD'), rowRef('NEW'))
          const old = op === 'i' ? 'NULL' : pgKey(table, source, rowRef('OLD'))
          const now = op === 'd' ? 'NULL' : pgKey(table, source, rowRef('NEW'))
          return `IF ${when} THEN INSERT INTO ${ORACLE_TABLE} (kind, source, op, old_key, new_key) VALUES (${literal(kind)}, ${index}, '${op}', ${old}, ${now}); END IF;`
        })
        .join('\n')
      out.push(
        `CREATE OR REPLACE FUNCTION ${fn}() RETURNS trigger LANGUAGE plpgsql AS $oracle$ BEGIN\n${body}\nRETURN NULL; END $oracle$`,
        `DROP TRIGGER IF EXISTS ${fn} ON ${quote(name)}`,
        `CREATE TRIGGER ${fn} AFTER ${event} ON ${quote(name)} FOR EACH ROW EXECUTE FUNCTION ${fn}()`,
      )
    }
  }
  return out
}

/** The statement that takes this transaction's shadow rows off the table. */
export const TAKE_ORACLE_ROWS = `DELETE FROM ${ORACLE_TABLE} RETURNING id, kind, source, op, old_key, new_key`

/** The statement that reads the write path's capture rows without draining them. */
export const READ_CAPTURE_ROWS =
  'SELECT id, kind, source, op, old_key, new_key FROM sync_capture ORDER BY id'

/** A capture row as either table holds it. */
export interface StoredCaptureRow {
  readonly id: number | string
  readonly kind: string
  readonly source: number | string
  readonly op: string
  readonly old_key: string | null
  readonly new_key: string | null
}

/** Stored rows as the drain hands them on. */
export function capturedRows(rows: readonly StoredCaptureRow[]): CapturedRow[] {
  return [...rows]
    .sort((a, b) => Number(a.id) - Number(b.id))
    .map((row) => ({
      id: Number(row.id),
      kind: row.kind,
      source: Number(row.source),
      op: row.op as CapturedRow['op'],
      oldKey: row.old_key === null ? null : (JSON.parse(row.old_key) as unknown[]),
      newKey: row.new_key === null ? null : (JSON.parse(row.new_key) as unknown[]),
    }))
}

/** A captured row without its id, as one line: what the comparison compares. */
export const captureLine = (row: Omit<CapturedRow, 'id'>): string =>
  `${row.kind}[${row.source}] ${row.op} ${JSON.stringify(row.oldKey)} -> ${JSON.stringify(row.newKey)}`

/**
 * How two captures differ as multisets of rows (ids and order aside): each line names
 * a row one side has more often than the other. Empty when they agree.
 */
export function captureDifference(
  expected: readonly Omit<CapturedRow, 'id'>[],
  actual: readonly Omit<CapturedRow, 'id'>[],
  names: { expected: string; actual: string } = { expected: 'oracle', actual: 'write path' },
): string[] {
  const counts = new Map<string, number>()
  for (const row of expected) counts.set(captureLine(row), (counts.get(captureLine(row)) ?? 0) + 1)
  for (const row of actual) counts.set(captureLine(row), (counts.get(captureLine(row)) ?? 0) - 1)
  const out: string[] = []
  for (const [line, count] of [...counts].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    if (count > 0) out.push(`only the ${names.expected} (${count}x): ${line}`)
    if (count < 0) out.push(`only the ${names.actual} (${-count}x): ${line}`)
  }
  return out
}

/** A write whose write-path capture differs from what the oracle's triggers saw. */
export class CaptureOracleDifference extends Error {
  override readonly name = 'CaptureOracleDifference'
  constructor(readonly lines: readonly string[]) {
    super(`the Postgres capture differs from the oracle's triggers:\n  ${lines.join('\n  ')}`)
  }
}

/** The SQL access the oracle needs inside the transaction it checks. */
export type OracleQuery = (text: string) => Promise<readonly StoredCaptureRow[]>

/**
 * Compare the transaction's write-path capture rows (`writePath`, as the drain returns
 * them) with its shadow rows, taking the shadow rows off; throws
 * {@link CaptureOracleDifference} when they differ. Call it where the drain runs.
 */
export async function checkAgainstOracle(
  query: OracleQuery,
  writePath: readonly CapturedRow[],
): Promise<void> {
  const shadow = capturedRows(await query(TAKE_ORACLE_ROWS))
  const lines = captureDifference(shadow, writePath)
  if (lines.length > 0) throw new CaptureOracleDifference(lines)
}

/**
 * A drain that checks the oracle: the drain's rows, after the shadow rows of the same
 * transaction were compared with them. For the Postgres leg's sync repository once the
 * store boots on Postgres (POD-6994): `drainCapture: oracleCheckedDrain(drain, query)`.
 */
export function oracleCheckedDrain(
  drain: (after?: number) => Promise<CapturedRow[]>,
  query: OracleQuery,
): (after?: number) => Promise<CapturedRow[]> {
  return async (after) => {
    const rows = await drain(after)
    await checkAgainstOracle(query, rows)
    return rows
  }
}
